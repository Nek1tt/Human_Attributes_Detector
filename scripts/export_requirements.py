"""Export pip installation profiles from the project's unchanged uv lockfile."""

import shutil
import subprocess
from pathlib import Path

import click

ROOT = Path(__file__).resolve().parents[1]
PROFILES = {
    "requirements.txt": (
        "NVIDIA CUDA 12.8 development and training",
        "cu128",
        (
            "gpu",
            "train",
            "dev",
            "vision",
            "api",
            "export",
        ),
    ),
    "requirements-cpu.txt": (
        "CPU development and ResNet training",
        "cpu",
        (
            "cpu",
            "train",
            "dev",
            "api",
            "export",
        ),
    ),
    "requirements/api-gpu.txt": (
        "NVIDIA CUDA 12.8 video API",
        "cu128",
        (
            "gpu",
            "vision",
            "api",
        ),
    ),
    "requirements/api-cpu.txt": ("CPU ResNet video API", "cpu", ("cpu", "api")),
}


@click.command()
@click.option("--check", is_flag=True, help="Fail if committed exports differ from uv.lock")
def main(check):
    executable = shutil.which("uv")
    portable = ROOT / "var/tools/uv.exe"
    if executable is None and portable.is_file():
        executable = str(portable)
    if executable is None:
        raise click.ClickException(
            "Install uv to regenerate requirements: python -m pip install uv"
        )
    outdated = []
    for filename, (description, torch_index, extras) in PROFILES.items():
        arguments = [
            executable,
            "export",
            "--locked",
            "--format",
            "requirements.txt",
            "--no-header",
            "--no-hashes",
            "--no-emit-project",
            "--emit-index-url",
            "--quiet",
        ]
        for extra in extras:
            arguments.extend(["--extra", extra])
        result = subprocess.run(  # noqa: S603 - fixed arguments to the located uv executable.
            arguments, cwd=ROOT, text=True, capture_output=True, check=True
        )
        # uv lists both configured PyTorch indexes; each pip profile needs only one.
        lines = [
            line
            for line in result.stdout.splitlines()
            if not line.startswith("--extra-index-url https://download.pytorch.org/whl/")
            or line == f"--extra-index-url https://download.pytorch.org/whl/{torch_index}"
        ]
        content = (
            "# Generated by python scripts/export_requirements.py from uv.lock.\n"
            f"# Profile: {description}.\n"
            "# Install from the repository root in a fresh virtual environment.\n"
            + "\n".join(lines).strip()
            + "\n\n-e .\n"
        )
        destination = ROOT / filename
        if check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != content:
                outdated.append(filename)
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8")
            click.echo(f"Exported {filename}")
    if outdated:
        raise click.ClickException("Regenerate requirements: " + ", ".join(outdated))
    if check:
        click.echo("All requirements profiles match uv.lock")


if __name__ == "__main__":
    main()
